import {useEffect,useState} from 'react';
import {Pencil,RefreshCw,Send,X} from 'lucide-react';
import type {MetadataItem,PLCConfig} from '../types';
import {userStorage} from '../../../src/shared/userStorage';
import {frameProtocol} from '../utils/frameProfile';

type Mapping={project?:string;hmiTarget?:string;sourceFingerprint?:string;dataInspect?:{schema:number;groups:{code:number;variants:{id:string;when:string;issues:string[]}[]}[]}};
type Preview={token:string;currentValue:number;expiresIn:number;condition:string;field:{type:string;min:string|null;max:string|null;variable:string};target:{ip:string;port:number;machineId:number}};
const input='w-full rounded border border-slate-600 bg-slate-800 p-2 text-sm text-white';
const button='rounded border border-slate-600 px-3 py-2 text-sm disabled:opacity-50';
function validMapping(value:unknown):value is Mapping{
 try{
  const next=value as Mapping;
  return next?.dataInspect?.schema===1&&Array.isArray(next.dataInspect.groups)&&!next.dataInspect.groups.some(g=>!g||!Array.isArray(g.variants)||g.variants.some(v=>!v||typeof v.id!=='string'||typeof v.when!=='string'||!Array.isArray(v.issues)));
 }catch{return false}
}

export function ParameterEditModal({item,plc,metadata,metadataSource,onClose,onWritten}:{item:MetadataItem;plc:PLCConfig;metadata:MetadataItem[];metadataSource:string;onClose:()=>void;onWritten:()=>void}){
 const key=`nami_write_${plc.id}`;
 const [saved]=useState(()=>{try{const value=JSON.parse(userStorage.getItem(key)||'{}');return value&&typeof value==='object'?value:{}}catch{return {}}});
 const [mapping,setMapping]=useState<Mapping|null>(validMapping(saved.mapping)?saved.mapping:null);
 const [port,setPort]=useState(String(saved.port||21011));
 const [variantId,setVariantId]=useState('');
 const [preview,setPreview]=useState<Preview|null>(null);
 const [value,setValue]=useState('');
 const [busy,setBusy]=useState<'read'|'send'|null>(null);
 const [error,setError]=useState('');
 const [message,setMessage]=useState('');
 const variants=mapping?.dataInspect?.groups.find(g=>g.code===item.groupCode)?.variants||[];
 const supported=frameProtocol(plc)==='spinconnect'&&!plc.isSimulated;
 useEffect(()=>{setPreview(null);setMessage('')},[mapping,port,variantId]);
 useEffect(()=>{setVariantId(variants.length===1?variants[0].id:'')},[mapping]);
 async function load(file?:File){
  if(!file)return;setError('');setPreview(null);setMessage('');
  try{
   if(file.size>2_000_000)throw new Error('Choose a write mapping smaller than 2 MB.');
   const next:Mapping=JSON.parse(await file.text());
   if(!validMapping(next))throw new Error('Choose write_mapping.json generated by the current ByteMap Write ST feature.');
   setMapping(next);
  }catch(reason){setMapping(null);setError(reason instanceof Error?reason.message:'Could not load this mapping.')}
 }
 async function request(url:string,data:unknown){
  const response=await fetch(url,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(data)});
  const json=await response.json();if(!response.ok)throw new Error(typeof json.detail==='string'?json.detail:'The edit request could not be completed.');return json;
 }
 async function read(){
  setBusy('read');setError('');setPreview(null);setMessage('');
  try{
   const next=await request('/api/nami/plc/prepare-edit',{plc,metadata,metadataSource,ip:plc.ip,port:plc.port,
    writePort:Number(port),machineId:plc.machineId,timeoutMs:plc.timeoutMs,isSimulated:plc.isSimulated,
    parameter:item,mapping,variantId});
   setPreview(next);setValue(String(next.currentValue));
   try{userStorage.setItem(key,JSON.stringify({mapping,port:Number(port)}))}catch{/* Browser storage is optional. */}
  }catch(reason){setError(reason instanceof Error?reason.message:'Could not read the settings.')}
  finally{setBusy(null)}
 }
 async function send(){
  if(!preview)return;setBusy('send');setError('');setMessage('');
  try{
   const result=await request('/api/nami/plc/send-edit',{token:preview.token,value});setPreview(null);
   if(result.success)setMessage(`${result.message} Value: ${result.observedValue}. Test ID: ${result.testId||'saved'}.`);
   else setError(`${result.error||'The selected value was not confirmed.'}${result.testId?` Test ID: ${result.testId}.`:''}`);
   if(result.writeAttempted)onWritten();
  }catch(reason){setPreview(null);setError(reason instanceof Error?reason.message:'Write outcome unknown. Read current settings before another attempt.')}
  finally{setBusy(null)}
 }
 return <div className="fixed inset-0 z-50 bg-black/70 flex items-center justify-center p-4" role="dialog" aria-modal="true" aria-labelledby="parameter-edit-title">
  <section className="w-full max-w-xl max-h-[90vh] overflow-y-auto rounded-xl border border-slate-700 bg-slate-900 p-5 text-slate-200 shadow-xl">
   <header className="flex justify-between items-start gap-3"><div><h2 id="parameter-edit-title" className="font-semibold flex gap-2 items-center"><Pencil size={17}/>Edit PLC parameter</h2><p className="mt-1 text-sm">{item.parameter} · GC {item.groupCode} · Tag {item.tagCode}</p></div><button type="button" aria-label="Close parameter editor" className={button} onClick={onClose} disabled={!!busy}><X size={18}/></button></header>
   <p className="my-3 text-sm text-slate-400">{plc.name} · {plc.ip} · Machine ID {plc.machineId} · {plc.endianness} endian</p>
   {!supported?<p role="status" className="text-amber-300">{frameProtocol(plc)==='ybs'?'YBS needs a verified settings write protocol. Its read frames cannot be used for B&R writes.':'The built-in measurement simulator has no settings write service. Select an Automation Studio or PLC write service.'}</p>:<div className="space-y-3">
    <p className="text-sm text-slate-400">Use the ByteMap mapping for this installed project and HMI configuration. Read current settings before sending a change.</p>
    <label className="block text-sm">Write mapping<input className="block mt-1 w-full text-sm" type="file" accept=".json,application/json" disabled={!!busy} onChange={e=>void load(e.target.files?.[0])}/></label>
    {mapping&&<p className="text-xs text-slate-400">{mapping.project} · HMI {mapping.hmiTarget} · Source {mapping.sourceFingerprint?.slice(0,12)}</p>}
    <label className="block text-sm">Settings TCP port<input aria-label="Settings TCP port" type="number" min="1" max="65535" value={port} onChange={e=>setPort(e.target.value)} disabled={!!busy} className={input}/></label>
    <label className="block text-sm">Machine configuration / write layout<select className={input} value={variantId} disabled={!!busy} onChange={e=>setVariantId(e.target.value)}><option value="">Select the matching layout</option>{variants.map(v=><option key={v.id} value={v.id} disabled={v.issues.length>0}>{v.when}{v.issues.length?' — source mapping needs review':''}</option>)}</select></label>
    {mapping&&!variants.length&&<p className="text-amber-300 text-sm">This mapping does not include GC {item.groupCode}. Generate this group in ByteMap.</p>}
    <button type="button" className={button+' flex gap-2 items-center'} onClick={()=>void read()} disabled={!!busy||!mapping||!variantId||!Number.isInteger(Number(port))||Number(port)<1||Number(port)>65535}><RefreshCw size={15} className={busy==='read'?'animate-spin':''}/>{busy==='read'?'Reading settings…':'Read current settings'}</button>
    {preview&&<div className="rounded-lg border border-emerald-700 p-3 space-y-3">
     <p className="text-sm">Current PLC value: <strong>{preview.currentValue}</strong> · {preview.field.type}</p>
     <label className="block text-sm">New PLC value (raw PLC units)<input autoFocus className={input} inputMode="decimal" value={value} disabled={!!busy} onChange={e=>setValue(e.target.value)}/></label>
     <p className="text-xs text-slate-400">Source limits: {preview.field.min??'PLC controlled'} to {preview.field.max??'PLC controlled'}. Display scaling is not applied to this raw value.</p>
     {!!item.dropdownOptions?.length&&<p className="text-xs">{item.dropdownOptions.map(o=>`${o.value}: ${o.label}`).join(' · ')}</p>}
     <p className="text-xs text-slate-400">Send to {preview.target.ip}:{preview.target.port}, Machine ID {preview.target.machineId}. The full group is preserved from a fresh read. Preview expires after {preview.expiresIn} seconds. The PLC applies its machine conditions and value checks.</p>
     <button type="button" className={button+' bg-emerald-700 text-white flex gap-2 items-center'} disabled={!!busy||!value.trim()||!Number.isFinite(Number(value))} onClick={()=>void send()}><Send size={15}/>{busy==='send'?'Sending and checking…':'Send to PLC and verify'}</button>
    </div>}
   </div>}
   {error&&<p role="alert" className="mt-4 text-sm text-rose-300 whitespace-pre-wrap">{error}</p>}
   {message&&<p role="status" className="mt-4 text-sm text-emerald-300">{message}</p>}
  </section>
 </div>
}
