import assert from 'node:assert/strict';
import {decodeRs485,RS485_FIELDS} from '../src/features/assist/rs485Decoder';
const frame=Array(56).fill(0);frame[0]=253;frame[1]=1;frame[2]=90;frame[3]=56;frame[6]=16;frame[7]=11;frame[8]=234;frame[9]=7;frame[20]=44;frame[21]=1;frame[54]=123;frame[55]=240;
const hex=(bytes:number[])=>bytes.map(n=>n.toString(16).padStart(2,'0')).join(' ');
const result=decodeRs485(hex(frame),'hex',true);
assert.equal(RS485_FIELDS.length,40);
assert.equal(result.captures.length,1);
assert.deepEqual(result.captures[0].issues,[]);
assert.equal(result.captures[0].rows.find(r=>r.parameter==='Shift year')?.decoded,'2026');
assert.equal(result.captures[0].rows.find(r=>r.offset==='20')?.decoded,'300');
assert.match(result.captures[0].rows.find(r=>r.offset==='54')!.finding,/not verified/);
assert.match(result.captures[0].rows[1].decoded,/RHS/);
assert.equal(decodeRs485(frame.join(' '),'decimal',true).captures[0].rows[18].decoded,'300');
assert.equal(decodeRs485(hex(frame).replaceAll(' ',''),'hex',true).captures.length,1);
const big=[...frame];big[3]=0;big[4]=56;big[8]=7;big[9]=234;
assert.equal(decodeRs485(hex(big),'hex',false).captures[0].rows[7].decoded,'2026');
const logs=`16/11/2026 09:10:00.123 [TX] - FD 01 5A\n16/11/2026 09:10:00.223 [RX] - ${hex(frame)}\n${hex(frame)}`;
const dock=decodeRs485(logs,'hex',true);assert.equal(dock.captures.length,2);assert.match(dock.notices.join(' '),/TX/);
assert.equal(decodeRs485(`TX - FD 01\n5A 00\nRX - ${hex(frame)}`,'hex',true).captures.length,1);
assert.match(decodeRs485(hex(frame.slice(0,24)),'hex',true).captures[0].issues.join(' '),/Incomplete/);
const bad=[...frame];bad[2]=91;bad[55]=0;bad[3]=57;
const unsupported=decodeRs485(hex(bad),'hex',true).captures[0];
assert.equal(unsupported.issues.length,3);assert.equal(unsupported.rows[4].decoded,'Not decoded');
assert.throws(()=>decodeRs485('253 999','decimal',true),/outside/);
assert.throws(()=>decodeRs485('FD GG','hex',true),/invalid/);
assert.throws(()=>decodeRs485('0'.repeat(1_000_001),'hex',true),/limit/);
assert.equal(decodeRs485('01 02','hex',true).captures.length,0);
console.log('RS-485: 40-field coverage, endian, Docklight RX/TX, multi-frame, truncation, unsupported GC, length, end-byte, CRC-unverified and input validation passed.');
